let lang = 'es';
const listeners = new Set();

export function detectLang(){
  const want = (navigator.languages || [navigator.language || 'en']).map(s => String(s).slice(0, 2).toLowerCase());
  for (const w of want) if (DICT[w]) return w;
  return 'en';
}
export function setLang(id){
  if (!DICT[id]) return;
  lang = id;
  document.documentElement.lang = id;
  listeners.forEach(fn => fn(id));
}
export const getLang = () => lang;
export const onLangChange = fn => { listeners.add(fn); return () => listeners.delete(fn); };

/** t('over.best', {v: 12}) -> 'Récord: 12' */
export function t(key, params){
  const table = DICT[lang] || DICT.en;
  let s = table[key];
  if (s === undefined) s = DICT.en[key] !== undefined ? DICT.en[key] : key;
  if (params) for (const k in params) s = s.split('{' + k + '}').join(params[k]);
  return s;
}
